/// <summary>
/// Rarity tiers for items in the gacha system.
/// Higher rarity = better stats and lower drop rate.
/// </summary>
public enum ItemRarity
{
    Common = 0,    // 60% drop rate, +5 style
    Rare = 1,      // 30% drop rate, +15 style
    Epic = 2,      // 9% drop rate, +40 style
    Legendary = 3  // 1% drop rate, +100 style
}
